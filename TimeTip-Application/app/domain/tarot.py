def _build_deck() -> tuple[TarotCard, ...]:
    cards = [TarotCard(name, "大阿卡那", upright, reversed) for name, upright, reversed in _MAJOR]
    for suit, (theme, element, ranks) in _SUITS.items():
        for rank, (upright, reversed) in ranks.items():
            cards.append(TarotCard(f"{suit}{rank}", f"小阿卡那 · {element} · {theme}", upright, reversed))
    return tuple(cards)


