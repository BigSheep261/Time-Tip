"""Pure data and rules for the offline Tarot reading feature.

The page deliberately keeps this module free of Qt so the deck and spread
definitions can be reused by tests or another presentation in the future.
"""
from __future__ import annotations

from dataclasses import dataclass
import random
from typing import Iterable


@dataclass(frozen=True)
class TarotCard:
    name: str
    arcana: str
    upright: str
    reversed: str


@dataclass(frozen=True)
class TarotPosition:
    title: str
    prompt: str
    reflection: str


@dataclass(frozen=True)
class TarotSpread:
    key: str
    title: str
    description: str
    positions: tuple[TarotPosition, ...]


