def draw(spread: TarotSpread, rng: random.Random | None = None) -> list[tuple[TarotCard, bool]]:
    """Draw unique cards; the bool marks a reversed orientation."""
    source = rng or random.SystemRandom()
    cards = source.sample(DECK, len(spread.positions))
    return [(card, bool(source.getrandbits(1))) for card in cards]


def orientation_label(reversed_: bool) -> str:
    return "逆位" if reversed_ else "正位"


def card_meaning(card: TarotCard, reversed_: bool) -> str:
    return card.reversed if reversed_ else card.upright


def position_interpretation(position: TarotPosition, card: TarotCard, reversed_: bool) -> str:
    meaning = card_meaning(card, reversed_).rstrip("。")
    return f"在「{position.title}」的位置，{card.name}{orientation_label(reversed_)}让你关注：{meaning}。{position.reflection}"


def reading_summary(spread: TarotSpread, drawn: Iterable[tuple[TarotCard, bool]]) -> str:
    """Tie each position to its actual meaning; orientation is not a good/bad score."""
    items = list(drawn)
    if not items:
        return "先选择一个牌阵并抽牌，给自己一点安静观察的时间。"
    if len(items) != len(spread.positions):
        raise ValueError("牌的数量必须与牌阵一致。")
    lines = [f"{position.title} · {card.name}（{orientation_label(reversed_)}）：{card_meaning(card, reversed_)}"
             for position, (card, reversed_) in zip(spread.positions, items)]
    prompts = {
        "single": "回到你的问题，选取一条有共鸣的提醒，化成今天可以尝试的小行动。",
        "timeline": "沿着过去 → 现在 → 未来阅读，找出你想延续或改变的模式，未来牌代表可调整的趋势。",
        "relationship": "先理解自己的状态，再以实际交流核对对方的表现，从相处建议中选一个双方可以尝试的行动。",
        "choice": "先看问题核心，再分别连读 A 的过程与走向、B 的过程与走向，比较投入与代价；不用正逆位数量判断哪条路更好。",
        "celtic": "先把现况与挑战一起看，再联系根基、目标和外部环境，最后用近期与最终走向检查当前行动是否符合期待。",
    }
    return "\n\n".join([*lines, prompts[spread.key]])
